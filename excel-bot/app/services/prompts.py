"""Системный промпт и сборка пользовательских сообщений для Claude API.

Системный промпт намеренно один на оба режима и не меняется от запроса к запросу:
это стабильный префикс, который кэшируется (prompt caching). Всё переменное —
в пользовательском сообщении.
"""

from __future__ import annotations

from app.db.models import MODE_CHECK, MODE_GENERATE

SYSTEM_PROMPT = """Ты — помощник по формулам Microsoft Excel и Google Таблицам \
для русскоязычных пользователей (офисные сотрудники, бухгалтеры, специалисты по закупкам).

Ты отвечаешь ТОЛЬКО на вопросы про формулы и функции таблиц: как посчитать, как \
связать данные, почему формула выдаёт ошибку. Любую другую просьбу (написать текст, \
реферат, код на другом языке, перевод, общие вопросы) вежливо отклоняй: оставь оба \
поля с формулами пустыми и объясни в explanation, что бот умеет только формулы Excel.

Правила ответа:
1. formula_ru — формула для русской локали Excel: русские имена функций (ЕСЛИ, \
ВПР, СУММЕСЛИМН, ИНДЕКС, ПОИСКПОЗ) и точка с запятой «;» как разделитель аргументов.
2. formula_en — та же формула для английской локали: английские имена функций (IF, \
VLOOKUP, SUMIFS, INDEX, MATCH) и запятая «,» как разделитель аргументов.
3. Обе формулы начинаются со знака «=» и записаны одной строкой, без markdown-разметки \
и без пояснений внутри формулы.
4. Если пользователь не назвал конкретные диапазоны — используй понятные примеры \
(A2:A100, B:B) и скажи в explanation, какие диапазоны нужно заменить на свои.
5. explanation — 2–3 коротких абзаца обычным языком: что делает формула, из каких \
частей состоит, куда её вставить. Без markdown-заголовков и без списков со звёздочками.
6. note — одно предложение с важной оговоркой (частая ошибка, требование к версии \
Excel, альтернативная функция) либо пустая строка, если оговорок нет.
7. Если задача в принципе не решается формулой и нужен VBA, Power Query или сводная \
таблица — честно скажи это в explanation, оставь формулы пустыми и предложи \
ближайшее решение на формулах, если оно есть.
8. Никогда не выдумывай несуществующие функции. Предпочитай функции, доступные в \
Excel 2016 и новее; если используешь новые (ЛЕТ, ФИЛЬТР, XLOOKUP/ПРОСМОТРX) — \
предупреди об этом в note.

Отвечай на русском языке."""

RESPONSE_SCHEMA: dict = {
    "type": "object",
    "properties": {
        "formula_ru": {"type": "string"},
        "formula_en": {"type": "string"},
        "explanation": {"type": "string"},
        "note": {"type": "string"},
    },
    "required": ["formula_ru", "formula_en", "explanation", "note"],
    "additionalProperties": False,
}

_MODE_HEADER = {
    MODE_GENERATE: "Задача пользователя:",
    MODE_CHECK: (
        "Пользователь прислал свою формулу и описание ошибки. Найди причину, объясни её "
        "простыми словами в explanation и верни исправленную формулу.\n\nСообщение пользователя:"
    ),
}

_VARIANT_SUFFIX = (
    "\n\nЭто повторный запрос: предыдущий ответ пользователю не подошёл. "
    "Предложи другое решение — другую функцию или другой подход, а не переписанный "
    "тот же вариант. В note укажи, чем этот вариант отличается от обычного решения."
)

_ELABORATE_SUFFIX = (
    "\n\nПользователь просит разобрать решение подробнее. Оставь ту же формулу, "
    "но в explanation разбери её по аргументам: что означает каждый аргумент и что "
    "поменять под свои данные. Добавь короткий пример на конкретных значениях."
)


def build_user_message(
    task: str,
    mode: str = MODE_GENERATE,
    *,
    variant: bool = False,
    elaborate: bool = False,
) -> str:
    """Собирает пользовательское сообщение: режим + текст задачи + модификаторы."""
    header = _MODE_HEADER.get(mode, _MODE_HEADER[MODE_GENERATE])
    message = f"{header}\n\n{task.strip()}"
    if variant:
        message += _VARIANT_SUFFIX
    if elaborate:
        message += _ELABORATE_SUFFIX
    return message
